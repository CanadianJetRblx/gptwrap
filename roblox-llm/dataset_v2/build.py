"""Build the v2 dataset from verified, permissively licensed GitHub Luau files.

Pipeline (each stage writes counts to the manifest, so every drop is explainable):

  1. select     GitHub records only; licence is SPDX-permissive (per repo, from the crawl metadata)
  2. split      repos are assigned to train or held-out by a stable hash (held-out never enters training)
  3. verify     verify.verify(): structure, engine API names, client/server boundary
  4. dedup      exact (normalised text) and per-repo cap, so one project cannot dominate
  5. score      quality features in [0, 1]
  6. tasks      debugging pairs (mutation -> verifier must catch it -> original is the fix) and
                header-comment -> code pairs. Every task records the checks that actually ran.

Nothing generated by a model is used. Every training response is a file that passed the checks.
"""
from __future__ import annotations

import hashlib
import json
import random
import re
from collections import Counter

from .verify import ApiIndex, verify

PERMISSIVE = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Unlicense", "CC0-1.0", "0BSD",
              "Zlib", "CC-BY-4.0"}
HOLDOUT_FRACTION = 0.05
PER_REPO_CAP = 150          # max training files from one repository
LICENCE_RE = re.compile(r"licen[cs]e|copyright|permission is hereby|all rights reserved|mit\b|apache", re.I)


def repo_bucket(repo: str) -> str:
    h = int(hashlib.sha1(repo.lower().encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return "holdout" if h < HOLDOUT_FRACTION else "train"


def normalise(text: str) -> str:
    text = re.sub(r"--\[(=*)\[.*?\]\1\]", "", text, flags=re.S)
    text = re.sub(r"--[^\n]*", "", text)
    return re.sub(r"\s+", " ", text).strip().lower()


def quality_score(text: str, v_warnings: list[str]) -> tuple[float, dict]:
    lines = [l for l in text.split("\n") if l.strip()]
    n = len(text)
    feats = {
        "chars": n,
        "functions": len(re.findall(r"\bfunction\b", text)),
        "typed": len(re.findall(r":\s*(number|string|boolean|Vector3|CFrame|Instance|Player|\{|\w+\?)\b", text)),
        "strict": text.lstrip().startswith("--!strict"),
        "uses_task": "task." in text,
        "deprecated_hits": len(v_warnings),
    }
    s = 0.0
    s += 0.25 if 600 <= n <= 20000 else (0.1 if 300 <= n <= 40000 else 0.0)
    s += min(0.2, 0.04 * feats["functions"])
    s += 0.15 if feats["typed"] >= 3 else (0.07 if feats["typed"] else 0.0)
    s += 0.1 if feats["strict"] else 0.0
    s += 0.1 if feats["uses_task"] else 0.0
    s += 0.2 if feats["deprecated_hits"] == 0 else 0.0
    return round(min(1.0, s), 3), feats


def comment_header(text: str) -> str | None:
    """Leading block of prose comments (not licence text), used as the task description."""
    lines = text.split("\n")
    out = []
    for ln in lines:
        s = ln.strip()
        if not s:
            if out:
                break
            continue
        if not s.startswith("--"):
            break
        body = s.lstrip("-").strip()
        if body.startswith("!") or not body:
            continue
        out.append(body)
    prose = [l for l in out if l and not LICENCE_RE.search(l)]
    if len(prose) < 3 or sum(len(l) for l in prose) < 120:
        return None
    return "\n".join(prose)


# ----------------------------------------------------------------------------- mutations

def _lines(text: str) -> list[str]:
    return text.split("\n")


def mutate(text: str, path: str, rng: random.Random) -> tuple[str, str] | None:
    """Apply one fault that the verifier can detect. Returns (mutant, kind) or None."""
    ops = ["typo_member", "typo_service", "typo_instance", "drop_end", "deprecated_task_wait"]
    if re.search(r"\.client\.|LocalScript", path, re.I) is None:
        ops = [o for o in ops]
    rng.shuffle(ops)
    for op in ops:
        if op == "typo_member":
            ms = list(re.finditer(r":\s*([A-Za-z_]\w{4,})\s*\(", text))
            if ms:
                m = rng.choice(ms)
                name = m.group(1)
                broken = name[:2] + name[3:] + "x" if len(name) > 4 else name + "x"
                return text[:m.start(1)] + broken + text[m.end(1):], op
        if op == "typo_service":
            ms = list(re.finditer(r'GetService\(\s*"([A-Za-z]\w+)"\s*\)', text))
            if ms:
                m = rng.choice(ms)
                name = m.group(1)
                return text[:m.start(1)] + name[:-1] + "x" + text[m.end(1):], op
        if op == "typo_instance":
            ms = list(re.finditer(r'Instance\.new\(\s*"([A-Za-z]\w+)"', text))
            if ms:
                m = rng.choice(ms)
                name = m.group(1)
                return text[:m.start(1)] + name[:-1] + "x" + text[m.end(1):], op
        if op == "drop_end":
            ls = _lines(text)
            ends = [i for i, l in enumerate(ls) if re.fullmatch(r"\s*end\s*", l)]
            if len(ends) >= 3:
                i = rng.choice(ends[1:-1])
                return "\n".join(ls[:i] + ls[i + 1:]), op
        if op == "deprecated_task_wait":
            if "task.wait(" in text:
                return text.replace("task.wait(", "wait(", 1), op
    return None


def build_debug_task(file_text: str, path: str, api: ApiIndex, rng: random.Random) -> dict | None:
    base = verify(path, file_text, api)
    if not base.ok or base.warnings:
        return None  # the fix must be clean: we only ever teach toward code that passes every check
    for _ in range(4):
        m = mutate(file_text, path, rng)
        if not m:
            return None
        mutant, op = m
        if mutant == file_text:
            continue
        v = verify(path, mutant, api)
        if v.ok and not v.warnings:
            continue  # mutation was not detected: skip (we never label undetected faults)
        report = (v.errors or v.warnings)[:3]
        prompt = (
            f"The Luau file `{path}` fails review. Verifier output:\n"
            + "\n".join(f"- {r}" for r in report)
            + "\n\nReturn the complete corrected file."
        )
        return {
            "task_type": "debug_detected_fault",
            "fault": op,
            "messages": [{"role": "user", "content": prompt + "\n\n```lua\n" + mutant + "\n```"},
                         {"role": "assistant", "content": "```lua\n" + file_text.rstrip() + "\n```"}],
            "checks_on_fix": base.checks,
            "fault_detected_by": v.checks,
            "verifier_output": report,
        }
    return None


def build_comment_task(file_text: str, path: str, header: str) -> dict:
    prompt = (f"Write a Roblox Luau {'server' if re.search(r'server', path, re.I) else 'module'} "
              f"that does the following (from the header comment of `{path}`):\n\n{header}")
    return {
        "task_type": "header_comment_to_code",
        "messages": [{"role": "user", "content": prompt},
                     {"role": "assistant", "content": "```lua\n" + file_text.rstrip() + "\n```"}],
    }


def build_iter(records, api: ApiIndex, emit_cpt, emit_sft, emit_holdout, seed: int = 7,
               debug_share: float = 0.25, max_tasks: int | None = None) -> dict:
    """Streaming build: `records` can be a generator, and each output row goes to an emitter as soon as
    it is produced, so memory does not grow with the dataset. Returns the manifest counts."""
    rng = random.Random(seed)
    man = Counter()
    per_repo = Counter()
    seen = set()
    n_sft = 0
    for r in records:
        man["seen"] += 1
        meta = r.get("meta") or {}
        lic = meta.get("license")   # recorded for provenance; not a filter (policy: licences do not gate training)
        if not meta.get("roblox_repo"):
            man["drop:not_roblox_repo"] += 1
            continue
        repo, path, text = meta.get("repo", ""), meta.get("path", ""), r["text"]
        bucket = repo_bucket(repo)
        v = verify(path, text, api)
        if not v.ok:
            man["drop:" + (v.errors[0].split(":")[0][:40] if v.errors else "verify")] += 1
            continue
        key = normalise(text)
        h = hashlib.sha1(key.encode()).hexdigest()
        if h in seen:
            man["drop:exact_duplicate"] += 1
            continue
        seen.add(h)
        q, feats = quality_score(text, v.warnings)
        base = {"id": r["id"], "repo": repo, "path": path, "licence": lic, "stars": meta.get("stars"),
                "checks": v.checks, "warnings": v.warnings, "quality": q, "features": feats}
        if bucket == "holdout":
            emit_holdout({**base, "text": text})
            man["holdout"] += 1
            continue
        if per_repo[repo] >= PER_REPO_CAP:
            man["drop:repo_cap"] += 1
            continue
        per_repo[repo] += 1
        emit_cpt({**base, "text": text})
        man["train_files"] += 1
        hdr = comment_header(text)
        if hdr:
            emit_sft({**base, **build_comment_task(text, path, hdr)})
            n_sft += 1
            man["task:header_comment"] += 1
        if rng.random() < debug_share:
            t = build_debug_task(text, path, api, rng)
            if t:
                emit_sft({**base, **t})
                n_sft += 1
                man["task:debug"] += 1
        if max_tasks and n_sft >= max_tasks:
            break
    return dict(man)


def build(records, api: ApiIndex, seed: int = 7, debug_share: float = 0.25, max_tasks: int | None = None):
    """List-returning wrapper around build_iter (used by tests and small runs)."""
    cpt, sft, hold = [], [], []
    man = build_iter(records, api, cpt.append, sft.append, hold.append, seed=seed,
                     debug_share=debug_share, max_tasks=max_tasks)
    return cpt, sft, hold, man
